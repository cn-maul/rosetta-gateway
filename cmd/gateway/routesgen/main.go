// Command routesgen writes the frontend mirror of the real production route
// contract assembled by cmd/gateway.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const marker = "ROUTE_CONTRACT:"

type routeContract struct {
	Pattern string `json:"pattern"`
	Public  bool   `json:"public"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	root, err := findModuleRoot()
	if err != nil {
		return err
	}

	cmd := exec.Command("go", "test", "./cmd/gateway",
		"-run", "^TestExportRouteContract$", "-count=1", "-v")
	cmd.Dir = root
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("export production route contract: %w\n%s", err, out)
	}

	idx := strings.LastIndex(string(out), marker)
	if idx < 0 {
		return fmt.Errorf("route contract marker %q not found:\n%s", marker, out)
	}
	line := strings.TrimSpace(string(out)[idx+len(marker):])
	if end := strings.IndexByte(line, '\n'); end >= 0 {
		line = line[:end]
	}

	var routes []routeContract
	if err := json.Unmarshal([]byte(line), &routes); err != nil {
		return fmt.Errorf("parse production route contract: %w\n%s", err, line)
	}
	sort.Slice(routes, func(i, j int) bool {
		return routes[i].Pattern < routes[j].Pattern
	})

	var src strings.Builder
	src.WriteString("// Code generated by go generate ./cmd/gateway; DO NOT EDIT.\n\n")
	src.WriteString("export interface ApiRouteContract {\n")
	src.WriteString("  pattern: string\n")
	src.WriteString("  public: boolean\n")
	src.WriteString("}\n\n")
	src.WriteString("export const API_ROUTES: readonly ApiRouteContract[] = [\n")
	for _, route := range routes {
		pattern, err := json.Marshal(route.Pattern)
		if err != nil {
			return fmt.Errorf("encode route pattern %q: %w", route.Pattern, err)
		}
		fmt.Fprintf(&src, "  { pattern: %s, public: %t },\n", pattern, route.Public)
	}
	src.WriteString("]\n")

	outPath := filepath.Join(root, "web", "src", "generated", "routes.ts")
	if err := os.WriteFile(outPath, []byte(src.String()), 0o644); err != nil {
		return fmt.Errorf("write generated route contract: %w", err)
	}
	return nil
}

func findModuleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("getwd: %w", err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found")
		}
		dir = parent
	}
}

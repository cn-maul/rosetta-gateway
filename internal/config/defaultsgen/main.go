// Command defaultsgen writes the browser-side mirrors of Go-owned defaults.
package main

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/cn-maul/rosetta-gateway/internal/config"
	"github.com/cn-maul/rosetta-gateway/internal/store"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	model := store.DefaultModelDefaults()
	runtime := config.Default().Defaults

	src := fmt.Sprintf(`// Code generated by go generate ./internal/config; DO NOT EDIT.

export interface ModelDefaultFallbackValues {
  default_context_window: number
  default_max_output_tokens: number
}

export interface RuntimeDefaultValues {
  upstream_timeout_ms: number
  stream_first_token_timeout_ms: number
  stream_idle_timeout_ms: number
  failover_max_targets: number
  failover_failure_threshold: number
}

export const MODEL_DEFAULT_FALLBACKS: ModelDefaultFallbackValues = {
  default_context_window: %d,
  default_max_output_tokens: %d,
}

export const RUNTIME_DEFAULTS: RuntimeDefaultValues = {
  upstream_timeout_ms: %d,
  stream_first_token_timeout_ms: %d,
  stream_idle_timeout_ms: %d,
  failover_max_targets: %d,
  failover_failure_threshold: %d,
}
`, model.ContextWindow, model.MaxOutputTokens,
		runtime.UpstreamTimeoutMs, runtime.StreamFirstTokenTimeoutMs,
		runtime.StreamIdleTimeoutMs, runtime.FailoverMaxTargets,
		runtime.FailoverFailureThreshold)

	out := filepath.Join("..", "..", "web", "src", "generated", "defaults.ts")
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return fmt.Errorf("create generated defaults directory: %w", err)
	}
	if err := os.WriteFile(out, []byte(src), 0o644); err != nil {
		return fmt.Errorf("write generated defaults: %w", err)
	}
	return nil
}

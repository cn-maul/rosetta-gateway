// Command contractgen exports JSON field contracts for Go DTOs annotated with
// @ts-type. The frontend test compares those fields with web/src/types.ts.
package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strconv"
	"strings"
)

const markerPrefix = "@ts-type "

type fieldContract struct {
	jsonName string
	embedded string
}

type typeContract struct {
	pkgDir string
	name   string
	target string
	fields []fieldContract
}

type contract struct {
	GoType string
	TS     string
	Fields []string
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	root, err := findModuleRoot()
	if err != nil {
		return err
	}
	types, marked, err := scanTypes(filepath.Join(root, "internal"))
	if err != nil {
		return err
	}
	sort.Slice(marked, func(i, j int) bool {
		if marked[i].pkgDir == marked[j].pkgDir {
			return marked[i].name < marked[j].name
		}
		return marked[i].pkgDir < marked[j].pkgDir
	})

	contracts := make([]contract, 0, len(marked))
	for _, t := range marked {
		fields, err := flattenFields(t, types)
		if err != nil {
			return err
		}
		contracts = append(contracts, contract{
			GoType: filepath.ToSlash(strings.TrimPrefix(t.pkgDir, root+string(filepath.Separator))) + "." + t.name,
			TS:     t.target,
			Fields: fields,
		})
	}

	var src strings.Builder
	src.WriteString("// Code generated by go generate ./internal/admin; DO NOT EDIT.\n\n")
	src.WriteString("export interface DTOFieldContract {\n")
	src.WriteString("  goType: string\n")
	src.WriteString("  tsType: string\n")
	src.WriteString("  fields: readonly string[]\n")
	src.WriteString("}\n\n")
	src.WriteString("export const DTO_CONTRACTS: readonly DTOFieldContract[] = [\n")
	for _, c := range contracts {
		fmt.Fprintf(&src, "  { goType: %s, tsType: %s, fields: [\n", strconv.Quote(c.GoType), strconv.Quote(c.TS))
		for _, field := range c.Fields {
			fmt.Fprintf(&src, "    %s,\n", strconv.Quote(field))
		}
		src.WriteString("  ] },\n")
	}
	src.WriteString("]\n")

	out := filepath.Join(root, "web", "src", "generated", "dto-contract.ts")
	if err := os.WriteFile(out, []byte(src.String()), 0o644); err != nil {
		return fmt.Errorf("write DTO contract: %w", err)
	}
	return nil
}

func scanTypes(root string) (map[string]map[string]typeContract, []typeContract, error) {
	types := make(map[string]map[string]typeContract)
	var marked []typeContract
	fset := token.NewFileSet()
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			if entry.Name() == "testdata" {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			return nil
		}
		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return err
		}
		dir := filepath.Dir(path)
		if types[dir] == nil {
			types[dir] = make(map[string]typeContract)
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}
				contract := typeContract{
					pkgDir: dir,
					name:   ts.Name.Name,
					target: markerTarget(ts.Doc, gen.Doc),
					fields: structFields(st),
				}
				types[dir][ts.Name.Name] = contract
				if contract.target != "" {
					marked = append(marked, contract)
				}
			}
		}
		return nil
	})
	return types, marked, err
}

func markerTarget(groups ...*ast.CommentGroup) string {
	for _, group := range groups {
		if group == nil {
			continue
		}
		for _, comment := range group.List {
			text := strings.TrimSpace(strings.TrimPrefix(comment.Text, "//"))
			if strings.HasPrefix(text, markerPrefix) {
				return strings.TrimSpace(strings.TrimPrefix(text, markerPrefix))
			}
		}
	}
	return ""
}

func structFields(st *ast.StructType) []fieldContract {
	var fields []fieldContract
	for _, field := range st.Fields.List {
		tag := ""
		if field.Tag != nil {
			raw, err := strconv.Unquote(field.Tag.Value)
			if err == nil {
				tag = reflect.StructTag(raw).Get("json")
			}
		}
		jsonName := strings.Split(tag, ",")[0]
		if jsonName == "-" {
			continue
		}
		if jsonName != "" {
			fields = append(fields, fieldContract{jsonName: jsonName})
			continue
		}
		if len(field.Names) == 0 {
			fields = append(fields, fieldContract{embedded: exprName(field.Type)})
			continue
		}
		for _, name := range field.Names {
			if name.IsExported() {
				fields = append(fields, fieldContract{jsonName: name.Name})
			}
		}
	}
	return fields
}

func flattenFields(t typeContract, types map[string]map[string]typeContract) ([]string, error) {
	seenTypes := make(map[string]bool)
	seenFields := make(map[string]bool)
	var out []string
	var visit func(typeContract) error
	visit = func(current typeContract) error {
		key := current.pkgDir + "\x00" + current.name
		if seenTypes[key] {
			return nil
		}
		seenTypes[key] = true
		for _, field := range current.fields {
			if field.embedded == "" {
				if !seenFields[field.jsonName] {
					seenFields[field.jsonName] = true
					out = append(out, field.jsonName)
				}
				continue
			}
			embedded, err := resolveEmbedded(current, field.embedded, types)
			if err != nil {
				return err
			}
			if err := visit(embedded); err != nil {
				return err
			}
		}
		return nil
	}
	if err := visit(t); err != nil {
		return nil, err
	}
	return out, nil
}

func resolveEmbedded(current typeContract, embedded string, types map[string]map[string]typeContract) (typeContract, error) {
	name := strings.TrimPrefix(embedded, "*")
	if dot := strings.LastIndex(name, "."); dot >= 0 {
		name = name[dot+1:]
		if found, ok := types[current.pkgDir][name]; ok {
			return found, nil
		}
		var match typeContract
		count := 0
		for _, pkg := range types {
			if found, ok := pkg[name]; ok {
				match = found
				count++
			}
		}
		if count == 1 {
			return match, nil
		}
		return typeContract{}, fmt.Errorf("resolve embedded field %s on %s: found %d candidates", embedded, current.name, count)
	}
	if found, ok := types[current.pkgDir][name]; ok {
		return found, nil
	}
	return typeContract{}, fmt.Errorf("resolve embedded field %s on %s", embedded, current.name)
}

func exprName(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.Ident:
		return e.Name
	case *ast.StarExpr:
		return "*" + exprName(e.X)
	case *ast.SelectorExpr:
		return exprName(e.X) + "." + e.Sel.Name
	default:
		return ""
	}
}

func findModuleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("getwd: %w", err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found")
		}
		dir = parent
	}
}
